-- ---------------------------------------------------------------------------
-- 6. Conteos para los filtros (security_invoker: respeta RLS de employees).
-- ---------------------------------------------------------------------------
create or replace view public.employee_group_counts with (security_invoker = true) as
select e.site, e.area_id, e.position_id, e.assignment_id, e.active, count(*)::int as total
from public.employees e
group by e.site, e.area_id, e.position_id, e.assignment_id, e.active;

revoke all on public.employee_group_counts from public, anon;
grant select on public.employee_group_counts to authenticated;

