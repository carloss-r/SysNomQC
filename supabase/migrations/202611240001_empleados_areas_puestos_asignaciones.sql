-- ---------------------------------------------------------------------------
-- 3. Sincronización empleado ↔ catálogos
-- ---------------------------------------------------------------------------
-- Nombre de catálogo: mayúsculas, sin espacios repetidos.
create or replace function public.employee_catalog_name(value text)
returns text language sql immutable set search_path = '' as $$
  select nullif(upper(regexp_replace(btrim(coalesce(value, '')), '\s+', ' ', 'g')), '');
$$;

-- security definer: da de alta puestos/asignaciones nuevos aunque el usuario no tenga permiso directo
-- sobre los catálogos (solo se ejecuta como trigger de employees, que ya pasó RLS).
create or replace function public.employees_sync_catalog()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_area_site text;
  v_name text;
  v_id bigint;
  v_site text;
  v_area bigint;
begin
  -- Área global: debe ser de la misma sede. Si la sede tiene áreas, es obligatoria al dar de alta
  -- o al cambiar de sede/área.
  if new.area_id is not null then
    select a.site into v_area_site from public.employee_areas a where a.id = new.area_id;
    if v_area_site is distinct from new.site then
      raise exception 'El área seleccionada no pertenece a la sede %.', new.site using errcode = 'P0001';
    end if;
  elsif (tg_op = 'INSERT' or new.site is distinct from old.site or new.area_id is distinct from old.area_id)
        and exists (select 1 from public.employee_areas a where a.site = new.site and a.active) then
    raise exception 'Selecciona el área global del trabajador (sede %).', new.site using errcode = 'P0001';
  end if;

  -- Puesto. Si solo cambió position_id, el nombre se toma del catálogo; en otro caso se busca por nombre.
  if tg_op = 'UPDATE' and new.position_id is distinct from old.position_id and new.position is not distinct from old.position
     and new.position_id is not null then
    select p.name, p.site, p.area_id into v_name, v_site, v_area from public.employee_positions p where p.id = new.position_id;
    if v_site is distinct from new.site or v_area is distinct from new.area_id then
      raise exception 'El puesto no corresponde a la sede y área del trabajador.' using errcode = 'P0001';
    end if;
    new.position := v_name;
  elsif tg_op = 'INSERT' or new.position_id is null or new.position is distinct from old.position
        or new.site is distinct from old.site or new.area_id is distinct from old.area_id then
    v_name := public.employee_catalog_name(new.position);
    if v_name is null then
      raise exception 'El puesto es obligatorio.' using errcode = 'P0001';
    end if;
    select p.id into v_id from public.employee_positions p
      where p.site = new.site and p.area_id is not distinct from new.area_id and p.name = v_name;
    if v_id is null then
      insert into public.employee_positions (site, area_id, name) values (new.site, new.area_id, v_name)
      on conflict on constraint employee_positions_key do update set active = true
      returning id into v_id;
    end if;
    new.position := v_name;
    new.position_id := v_id;
  end if;

  -- Asignación (opcional). Mismas reglas que el puesto.
  v_id := null;
  if tg_op = 'UPDATE' and new.assignment_id is distinct from old.assignment_id and new.assignment is not distinct from old.assignment
     and new.assignment_id is not null then
    select s.name, s.site, s.area_id into v_name, v_site, v_area from public.employee_assignments s where s.id = new.assignment_id;
    if v_site is distinct from new.site or v_area is distinct from new.area_id then
      raise exception 'La asignación no corresponde a la sede y área del trabajador.' using errcode = 'P0001';
    end if;
    new.assignment := v_name;
  elsif tg_op = 'INSERT' or new.assignment is distinct from old.assignment or new.assignment_id is distinct from old.assignment_id
        or new.site is distinct from old.site or new.area_id is distinct from old.area_id
        or (new.assignment_id is null and new.assignment is not null) then
    v_name := public.employee_catalog_name(new.assignment);
    if v_name is null then
      new.assignment := null;
      new.assignment_id := null;
    else
      select s.id into v_id from public.employee_assignments s
        where s.site = new.site and s.area_id is not distinct from new.area_id and s.name = v_name;
      if v_id is null then
        insert into public.employee_assignments (site, area_id, name) values (new.site, new.area_id, v_name)
        on conflict on constraint employee_assignments_key do update set active = true
        returning id into v_id;
      end if;
      new.assignment := v_name;
      new.assignment_id := v_id;
    end if;
  end if;

  return new;
end;
$$;
revoke all on function public.employees_sync_catalog() from public, anon, authenticated;

drop trigger if exists employees_sync_catalog on public.employees;
create trigger employees_sync_catalog
before insert or update of site, area_id, position, position_id, assignment, assignment_id on public.employees
for each row execute function public.employees_sync_catalog();

-- Renombrar un puesto/asignación en el catálogo actualiza la copia del nombre en los trabajadores.
create or replace function public.employee_catalog_rename()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.name is distinct from old.name then
    if tg_table_name = 'employee_positions' then
      update public.employees set position = new.name where position_id = new.id;
    else
      update public.employees set assignment = new.name where assignment_id = new.id;
    end if;
  end if;
  return new;
end;
$$;
revoke all on function public.employee_catalog_rename() from public, anon, authenticated;

drop trigger if exists employee_positions_rename on public.employee_positions;
create trigger employee_positions_rename after update of name on public.employee_positions
for each row execute function public.employee_catalog_rename();
drop trigger if exists employee_assignments_rename on public.employee_assignments;
create trigger employee_assignments_rename after update of name on public.employee_assignments
for each row execute function public.employee_catalog_rename();

