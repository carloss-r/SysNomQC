-- Empleados: áreas globales (CYM y CAL), puestos y asignaciones como catálogos relacionados.
-- Ejecutar DESPUÉS de 202611210002_epp_entregar_con_compra_pendiente.sql. Es seguro repetirla.
--
--   * employee_areas: áreas globales de una sede (Campeche: CYM y CAL).
--   * employee_positions / employee_assignments: catálogos por sede y área. Un puesto con el mismo nombre
--     en CYM y en CAL son dos registros distintos (p. ej. "AUXILIAR GENERAL" de cada área).
--   * employees.area_id / position_id / assignment_id: llaves a los catálogos. Las columnas de texto
--     "position" y "assignment" se conservan como copia del nombre (las usan EPP, el buscador y los
--     reportes) y las mantiene la base: el trigger busca el puesto/asignación por nombre en la sede y
--     área del trabajador y, si no existe, lo da de alta en el catálogo.
--   * Carga inicial de Campeche según las listas CAMPECHE_CAL.TXT y CAMPECHECYM.TXT (por ID de empleado).
--   * employee_group_counts: conteos por sede / área / puesto / asignación / estatus en una consulta
--     (alimenta los filtros de la pantalla con su número de trabajadores).

-- ---------------------------------------------------------------------------
-- 1. Catálogos
-- ---------------------------------------------------------------------------
create table if not exists public.employee_areas (
  id bigint generated by default as identity primary key,
  site text not null,
  code text not null,
  name text not null,
  responsible text,
  sort_order smallint not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint employee_areas_site_check check (site in ('Campeche', 'Lagunas', 'Cruz Azul', 'El Carmen')),
  constraint employee_areas_code_check check (code ~ '^[A-Z0-9]{2,10}$'),
  constraint employee_areas_name_check check (char_length(name) between 1 and 80),
  constraint employee_areas_responsible_check check (responsible is null or char_length(responsible) <= 150),
  constraint employee_areas_site_code_key unique (site, code)
);

create table if not exists public.employee_positions (
  id bigint generated by default as identity primary key,
  site text not null,
  area_id bigint references public.employee_areas (id) on delete restrict,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint employee_positions_name_check check (char_length(name) between 1 and 150),
  constraint employee_positions_key unique nulls not distinct (site, area_id, name)
);

create table if not exists public.employee_assignments (
  id bigint generated by default as identity primary key,
  site text not null,
  area_id bigint references public.employee_areas (id) on delete restrict,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint employee_assignments_name_check check (char_length(name) between 1 and 150),
  constraint employee_assignments_key unique nulls not distinct (site, area_id, name)
);

comment on table public.employee_areas is 'Áreas globales por sede (Campeche: CYM y CAL).';
comment on table public.employee_positions is 'Catálogo de puestos por sede y área global.';
comment on table public.employee_assignments is 'Catálogo de asignaciones por sede y área global.';

