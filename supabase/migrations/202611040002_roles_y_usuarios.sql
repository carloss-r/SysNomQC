-- Roles y usuarios administrables desde /admin, sobre las tablas que ya existen en la BD:
--   public.roles (id_rol, nombre, descripcion)  y  public.authorized_users.
-- Idempotente. Requiere 202611030001_create_employee_directory.sql.

-- Limpieza de una versión previa de esta migración (app_roles), si llegó a ejecutarse.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'authorized_users'
      and column_name = 'role_id' and data_type = 'uuid'
  ) then
    alter table public.authorized_users drop column role_id;
  end if;
end;
$$;
drop table if exists public.app_roles;

-- En la nube esta tabla ya existe; se crea solo para bases nuevas (p. ej. local).
create table if not exists public.roles (
  id_rol integer generated by default as identity primary key,
  nombre character varying not null unique,
  descripcion text
);

alter table public.roles add column if not exists permisos text[] not null default '{}';
alter table public.roles add column if not exists es_sistema boolean not null default false;

insert into public.roles (nombre, descripcion)
values
  ('Super administrador', 'Control total y global de todas las sedes'),
  ('Administrador de sede', 'Administración específica para su sede asignada'),
  ('Recursos humanos', 'Altas, bajas y gestión de expedientes'),
  ('Almacenista de EPP', 'Control de stock y entregas de equipo de protección')
on conflict (nombre) do nothing;

update public.roles set es_sistema = true,
  permisos = array['employees.view','employees.create','employees.edit','employees.delete','employees.download','users.manage']
where nombre = 'Super administrador';
update public.roles set permisos = array['employees.view','employees.create','employees.edit','employees.delete','employees.download']
where nombre in ('Administrador de sede', 'Recursos humanos') and permisos = '{}';
update public.roles set permisos = array['employees.view']
where nombre = 'Almacenista de EPP' and permisos = '{}';

alter table public.authorized_users add column if not exists full_name text;
alter table public.authorized_users
  add column if not exists role_id integer references public.roles (id_rol) on delete restrict;

-- Cuentas ya autorizadas: el dueño queda como SuperAdmin; las demás como RecursosHumanos
-- (solo expedientes). Cámbialo después desde /admin.
update public.authorized_users
set role_id = (select id_rol from public.roles where nombre = 'Super administrador')
where role_id is null and lower(email) = 'crlos.trabajo.dev@gmail.com';

update public.authorized_users
set role_id = (select id_rol from public.roles where nombre = 'Recursos humanos')
where role_id is null;

-- Seguridad: la app lee roles con la sesión del usuario; todo cambio va por el servidor.
alter table public.roles enable row level security;
revoke all on public.roles from public, anon, authenticated;
grant select on public.roles to authenticated;
drop policy if exists "Authorized users can read roles" on public.roles;
create policy "Authorized users can read roles"
on public.roles for select to authenticated
using (public.is_employee_app_user());

-- public.usuarios guarda password_hash y la app no la usa (el acceso es con Supabase Auth):
-- se bloquea para anon/authenticated.
do $$
begin
  if to_regclass('public.usuarios') is not null then
    alter table public.usuarios enable row level security;
    revoke all on public.usuarios from public, anon, authenticated;
  end if;
end;
$$;
